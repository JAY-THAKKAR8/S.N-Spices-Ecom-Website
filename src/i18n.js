const saved = (() => { try { return localStorage.getItem('sn_lang'); } catch { return null; } })();

i18n.use(initReactI18next).init({
  resources,
  lng: saved || 'en',
  fallbackLng: 'en',
  defaultNS: 't',
  interpolation: { escapeValue: false },
});

const setHtmlLang = (l) => document.documentElement.setAttribute('lang', l);
setHtmlLang(i18n.language);
i18n.on('languageChanged', (l) => {
  setHtmlLang(l);
  try { localStorage.setItem('sn_lang', l); } catch { /* ignore */ }
});

export default i18n;
